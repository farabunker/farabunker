"""
DB-backed binding provider -- `models.registry.bindings.db_provider`, and
its pk-addressed twin `resolve_connection`.

`db_provider` is the "db" half of `models.contracts.bindings.resolve()`'s db ->
env fallback chain (see that module's docstring), and the default
`settings.INFERENCE_BINDING_PROVIDER` (Ruling 2). It answers "which
`ModelConnection` is bound to this role right now?" from the console's own
tables (`models.registry.models`); when it has no opinion -- no binding
row, an unbound (`connection=None`) binding, or the tables not existing yet
(mid-`migrate`, before this app's own migrations have run) -- it returns
`None` and `resolve()` falls back to `env_provider`, so an operator who
pinned a role from the environment (`LLM_MODEL`/`EMBED_MODEL`) still
resolves with no DB rows at all. With neither a binding row nor an explicit
environment override, `resolve()` raises and the role is honestly
unassigned -- there is no baked default to land on (ADR 0010 third
amendment).

`resolve_connection` answers a different question: "resolve THIS specific,
operator-chosen `ModelConnection` (by pk), for this capability" -- the seam
a caller-supplied override (e.g. the Ask-time model picker) resolves
through, independent of whatever role binding is currently durable. Unlike
`db_provider` it does not degrade to `None`; a pk that doesn't resolve to a
usable connection is a caller error, so it raises the same `ValueError`
`models.contracts.bindings.resolve()` and `models.contracts.engines.get_engine()`
already raise for "nothing usable here" -- there is no second exception type
for the same kind of failure.

Both providers build their `ResolvedModel` through the single
`resolved_from_connection()` helper below, so the field-by-field
construction (in particular, the `context_window`-only-when-set rule) can
never drift between the role-keyed and pk-keyed paths.

A few small reads live alongside `resolve_connection`, all for a per-request
model picker and its "answered by" / "generated by" line rather than for
resolution itself: `connections_for_picker(capability)` (the general
picker's option list -- `ModelConnection.objects.picker_order()` filtered
in Python to capability membership; `chat_connections_for_picker()` is now
a thin wrapper over it, kept as tools/rag's original name), `role_primary
(role_key)` (which connection -- or explicit environment override --
currently answers `role_key`, so a picker can mark/preselect it and a job
can name it on the un-overridden path once it actually finishes;
`answer_role_primary()` is a thin wrapper over it for
`models.contracts.roles.RAG_ANSWER_ROLE`, kept for the same reason). Both
generalized forms exist because `tools/vision` is now a second caller of
this same picker surface, alongside tools/rag -- one picker-option rule
and one role-primary rule, not a second copy per module. And
`resolve_connection_named()` (the same pk-addressed resolution
as `resolve_connection`, paired with the connection's display name in the
one query, for the overridden path -- avoiding a separate bare-name lookup
that would re-query the same row `resolve_connection` had just fetched). This
file is each §5 module's ONE console-side import surface for its picker
feature -- tools/rag (Ask-time) and now tools/vision reach here, never
into `models.registry.models` directly.

`footprint_for()` is a different kind of small read: not for the Ask
picker at all, but THE single path from a model ref (engine, endpoint,
model_id) to a memory footprint -- the execution queue's future claim code
never reads `ModelConnection.effective_footprint_bytes` directly, only
through this function, so there is exactly one place that "what does this
model cost to hold in memory" question is answered.

`record_measured_footprint()` is `footprint_for()`'s write-side twin (T4):
the worker's post-execution measurement writes `measured_footprint_bytes`/
`measured_footprint_at` through here, using the EXACT SAME match rule
(engine exact, endpoint `norm_endpoint`-normalized on both sides, model_id
exact) so a measurement can only ever land on the one row `footprint_for`
would itself have resolved for that same ref -- never a different row an
independently-written match rule might disagree with. Both it and its
rung-3 twin `record_engine_reported_footprint()` (spec §3.1) now go
through one shared writer, `_record_footprint`, which KEEPS THE MAXIMUM
(spec §3.2): a reading below the column's own standing value is refused
outright -- neither the bytes nor the timestamp are written -- rather
than tolerated within a band, because two live incidents show a
percentage band ratchets a standing value down over repeated warm runs
instead of preventing exactly that.

Imports are lazy and local to each function on purpose: Django's app
registry / DB access must not happen at import time (this keeps
`apps.py::ready()` and module import light, and matches
`models.contracts.bindings.resolve()`'s own lazy, per-call provider import).
"""
from __future__ import annotations

import logging
from typing import TYPE_CHECKING

logger = logging.getLogger(__name__)

# Below this ratio, a refused lowering is an OPERATOR-ACTIONABLE event
# (WARNING) rather than a note (INFO): a reading under three quarters of
# the standing value is the shape both live incidents took (26.4 -> 6.4
# GB, 15.2 -> 11.1 GB), and the operator's remedy -- set
# `footprint_override_bytes` -- is named in the line itself. A smaller dip
# is ordinary measurement noise and is recorded at INFO, so the refusal is
# still visible without teaching an operator to ignore warnings.
#
# A THRESHOLD FOR LOG LEVEL ONLY. No reading below the standing value is
# ever written, at any ratio: a tolerance band measured against the
# standing value ratchets geometrically and reproduces the exact incident
# this rule exists to refuse (spec §3.2).
FOOTPRINT_DIP_WARNING_RATIO = 0.75

# RE-EXPORTED, not re-implemented. `bindings` is the one submodule of this
# package every other column may import (the import-law gate names it by
# path), so the model-access question has to be reachable here or a caller
# would have to break that rule to ask it.
